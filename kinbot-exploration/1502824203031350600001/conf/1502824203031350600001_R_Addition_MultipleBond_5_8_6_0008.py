db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502824203031350600001/kinbot.db')
label = 'conf/1502824203031350600001_R_Addition_MultipleBond_5_8_6_0008'
logfile = 'conf/1502824203031350600001_R_Addition_MultipleBond_5_8_6_0008.log'

mol = Atoms(symbols=[np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')], positions=[[np.float64(3.0709554087300623), np.float64(0.7528199258313574), np.float64(1.9409154936683477)], [np.float64(3.245991974170122), np.float64(-0.6032058665948152), np.float64(1.7847972151263438)], [np.float64(1.921022599656664), np.float64(1.0354681604936316), np.float64(2.649146003534213)], [np.float64(4.163699634644567), np.float64(1.276998648250867), np.float64(2.6436945935682794)], [np.float64(3.10595212304513), np.float64(1.6947105910445377), np.float64(0.17634471184280048)], [np.float64(0.9900941606418047), np.float64(0.0), np.float64(0.0)], [np.float64(3.8555982694721256), np.float64(0.6631046865328578), np.float64(-0.7619576345071359)], [np.float64(1.1567372711880255), np.float64(1.590878814546375), np.float64(0.0)], [np.float64(0.0), np.float64(0.0), np.float64(0.0)]])

kwargs = {'method': 'mp2', 'basis': '6-31G', 'nprocshared': 8, 'mem': '700MW', 'label': 'conf/1502824203031350600001_R_Addition_MultipleBond_5_8_6_0008', 'Symm': 'None', 'mult': 1, 'charge': 0, 'scf': 'xqc', 'pop': 'None', 'guess': 'Mix,Always', 'opt': 'NoFreeze,TS,CalcAll,NoEigentest,MaxCycle=999'}
