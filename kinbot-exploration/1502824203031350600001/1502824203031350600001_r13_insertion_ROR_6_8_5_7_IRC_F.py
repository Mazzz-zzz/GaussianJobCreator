db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502824203031350600001/kinbot.db')
label = '1502824203031350600001_r13_insertion_ROR_6_8_5_7_IRC_F'
logfile = '1502824203031350600001_r13_insertion_ROR_6_8_5_7_IRC_F.log'

