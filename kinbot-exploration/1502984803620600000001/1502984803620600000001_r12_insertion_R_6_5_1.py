db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984803620600000001/kinbot.db')
label = '1502984803620600000001_r12_insertion_R_6_5_1'
logfile = '1502984803620600000001_r12_insertion_R_6_5_1.log'

atom = [np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')]
geom = [[np.float64(0.052177), np.float64(-0.123157), np.float64(0.123126)], [np.float64(-0.786454), np.float64(0.32586), np.float64(-0.830646)], [np.float64(-0.412335), np.float64(0.481986), np.float64(1.19612)], [np.float64(-0.274864), np.float64(-1.39975), np.float64(0.196597)], [np.float64(1.798788), np.float64(0.156155), np.float64(-0.21052)], [np.float64(1.506149), np.float64(-0.599945), np.float64(1.249466)], [np.float64(2.318063), np.float64(-0.204918), np.float64(-1.384685)], [np.float64(2.100271), np.float64(1.627231), np.float64(-0.017813)], [np.float64(2.321497), np.float64(2.262828), np.float64(-0.715391)]]
