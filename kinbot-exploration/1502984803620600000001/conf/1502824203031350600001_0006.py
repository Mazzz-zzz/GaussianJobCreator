import numpy as np
from ase import Atoms
from ase.db import connect

from kinbot.ase_modules.calculators.gaussian import Gaussian
from kinbot import reader_gauss
from kinbot.utils import iowait

db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984803620600000001/kinbot.db')
label = 'conf/1502824203031350600001_0006'
logfile = 'conf/1502824203031350600001_0006.log'

mol = Atoms(symbols=['C', 'F', 'F', 'F', 'S', 'O', 'O', 'O', 'H'], positions=[[np.float64(0.6426489874196895), np.float64(3.8189376470000935), np.float64(0.6699299912959925)], [np.float64(1.502574099080061), np.float64(4.212012201464368), np.float64(-0.23847996083994075)], [np.float64(1.2494224113838746), np.float64(3.691151660992378), np.float64(1.8364780650181238)], [np.float64(-0.3163065047711777), np.float64(4.71915778533727), np.float64(0.7804419864013393)], [np.float64(-0.19922933980299629), np.float64(2.180950953237181), np.float64(0.19664790295715098)], [np.float64(0.9663875567193526), np.float64(0.0), np.float64(0.0)], [np.float64(-0.7920398003674695), np.float64(2.478592745741529), np.float64(-1.0865928322044691)], [np.float64(1.2490131048205664), np.float64(1.3966039906814989), np.float64(0.0)], [np.float64(0.0), np.float64(0.0), np.float64(0.0)]])

