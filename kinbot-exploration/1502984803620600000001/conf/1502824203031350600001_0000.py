db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984803620600000001/kinbot.db')
label = 'conf/1502824203031350600001_0000'
logfile = 'conf/1502824203031350600001_0000.log'

mol = Atoms(symbols=['C', 'F', 'F', 'F', 'S', 'O', 'O', 'O', 'H'], positions=[[np.float64(-0.7197361802209177), np.float64(1.874076062910915), np.float64(-1.6063096375022448)], [np.float64(-0.6811189959171892), np.float64(0.6018321732956207), np.float64(-1.9210978878928802)], [np.float64(0.05957788782197376), np.float64(2.5618040884822375), np.float64(-2.42180789056488)], [np.float64(-1.9586760243355334), np.float64(2.314193690229731), np.float64(-1.7226254632591353)], [np.float64(-0.1992293398029954), np.float64(2.180950953237181), np.float64(0.19664790295715096)], [np.float64(0.9663875567193527), np.float64(0.0), np.float64(0.0)], [np.float64(-1.1218593258392635), np.float64(1.360002835437733), np.float64(0.9459941246239184)], [np.float64(1.2490131048205668), np.float64(1.3966039906814989), np.float64(0.0)], [np.float64(0.0), np.float64(0.0), np.float64(0.0)]])

