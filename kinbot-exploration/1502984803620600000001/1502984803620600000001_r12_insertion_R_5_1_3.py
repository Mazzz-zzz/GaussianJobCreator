db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984803620600000001/kinbot.db')
label = '1502984803620600000001_r12_insertion_R_5_1_3'
logfile = '1502984803620600000001_r12_insertion_R_5_1_3.log'

atom = [np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')]
geom = [[np.float64(-0.001872), np.float64(-0.587267), np.float64(-0.210495)], [np.float64(-0.660573), np.float64(-0.779345), np.float64(-1.309427)], [np.float64(0.123992), np.float64(1.482471), np.float64(0.52457)], [np.float64(-0.670431), np.float64(-1.148089), np.float64(0.73342)], [np.float64(1.440567), np.float64(0.238958), np.float64(-0.050103)], [np.float64(1.987415), np.float64(-0.82477), np.float64(0.767253)], [np.float64(1.634129), np.float64(0.462222), np.float64(-1.481435)], [np.float64(2.378113), np.float64(1.398946), np.float64(0.51705)], [np.float64(2.391946), np.float64(2.283164), np.float64(0.11542)]]
