db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984803620600000001/kinbot.db')
label = '1502984803620600000001_r12_insertion_R_2_1_3'
logfile = '1502984803620600000001_r12_insertion_R_2_1_3.log'

atom = [np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')]
geom = [[np.float64(-0.778428), np.float64(-0.6567), np.float64(-0.193972)], [np.float64(-1.159582), np.float64(0.428634), np.float64(-1.404624)], [np.float64(-1.265519), np.float64(1.453772), np.float64(0.19158)], [np.float64(-1.808112), np.float64(-1.254504), np.float64(0.027376)], [np.float64(0.869115), np.float64(-0.543311), np.float64(0.291547)], [np.float64(0.868394), np.float64(-0.776058), np.float64(1.754128)], [np.float64(1.648006), np.float64(-1.374768), np.float64(-0.64697)], [np.float64(1.17555), np.float64(1.035719), np.float64(-0.040699)], [np.float64(0.440577), np.float64(1.687217), np.float64(0.012399)]]
