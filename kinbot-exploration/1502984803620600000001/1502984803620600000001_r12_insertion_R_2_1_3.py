db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984803620600000001/kinbot.db')
label = '1502984803620600000001_r12_insertion_R_2_1_3'
logfile = '1502984803620600000001_r12_insertion_R_2_1_3.log'

atom = [np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')]
geom = [[np.float64(0.287574), np.float64(-0.500873), np.float64(-0.1486)], [np.float64(-0.586866), np.float64(0.641007), np.float64(-0.997339)], [np.float64(-0.411588), np.float64(1.385416), np.float64(0.741952)], [np.float64(-0.506086), np.float64(-1.308385), np.float64(0.188546)], [np.float64(1.932513), np.float64(-0.091588), np.float64(-0.08354)], [np.float64(2.394467), np.float64(-0.522096), np.float64(1.214854)], [np.float64(2.528028), np.float64(-0.579161), np.float64(-1.318239)], [np.float64(1.872816), np.float64(1.494184), np.float64(-0.154806)], [np.float64(1.112435), np.float64(2.00779), np.float64(0.163426)]]
