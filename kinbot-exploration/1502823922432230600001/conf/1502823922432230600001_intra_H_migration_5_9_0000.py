mol = Atoms(symbols=[np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')], positions=[[np.float64(2.5287558412701907), np.float64(2.133925767035657), np.float64(-1.115716503245538)], [np.float64(3.4207966372637326), np.float64(1.3212255909578836), np.float64(-1.666444783075406)], [np.float64(3.134476259637199), np.float64(3.237530936698573), np.float64(-0.7401003776524243)], [np.float64(1.622925617937252), np.float64(2.429158303817718), np.float64(-2.0211254219352246)], [np.float64(1.465936465886568), np.float64(0.0), np.float64(0.0)], [np.float64(2.621297873007096), np.float64(-0.8265159782366223), np.float64(0.07900241244437511)], [np.float64(1.9693501212100881), np.float64(1.5750487185083553), np.float64(0.0)], [np.float64(0.6661152117649546), np.float64(-0.008793180369247993), np.float64(-1.2648690262237918)], [np.float64(0.0), np.float64(0.0), np.float64(0.0)]])

kwargs = {'method': 'bmk', 'basis': '6-31++G(2df,p)', 'nprocshared': 8, 'mem': '700MW', 'label': 'conf/1502823922432230600001_intra_H_migration_5_9_0000', 'Symm': 'None', 'mult': 1, 'charge': 0, 'scf': 'xqc', 'pop': 'None', 'opt': 'NoFreeze,TS,CalcAll,NoEigentest,MaxCycle=999'}
