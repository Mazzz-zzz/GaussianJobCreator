logfile = 'conf/1502663602461501180601_0019.log'

mol = Atoms(symbols=['C', 'F', 'F', 'F', 'S', 'O', 'O', 'O', 'H'], positions=[[np.float64(-1.8876878411106839), np.float64(0.42167003077766485), np.float64(0.026226579936120847)], [np.float64(-2.718273578682012), np.float64(-0.12476614178747747), np.float64(0.8871439425072655)], [np.float64(-1.0686597953605848), np.float64(-0.5115832931859043), np.float64(-0.42967907624695456)], [np.float64(-2.5808405228347064), np.float64(0.8896680321377375), np.float64(-0.9987179050974687)], [np.float64(-0.08942789928082107), np.float64(2.294385697141459), np.float64(-0.16183963060598625)], [np.float64(0.9665283253629964), np.float64(0.0), np.float64(0.0)], [np.float64(-1.2190248696051278), np.float64(1.4137815704642145), np.float64(0.6824322984750133)], [np.float64(1.2362695567356892), np.float64(1.4280459592287444), np.float64(0.0)], [np.float64(0.0), np.float64(0.0), np.float64(0.0)]])

