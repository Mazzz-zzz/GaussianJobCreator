logfile = '1502663602461501180601_well.log'

mol = Atoms(symbols=[np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')], positions=[[np.float64(0.612137), np.float64(0.39628), np.float64(-1.050324)], [np.float64(1.844911), np.float64(0.192622), np.float64(-1.460733)], [np.float64(0.545318), np.float64(1.582128), np.float64(-0.468157)], [np.float64(-0.191038), np.float64(0.413983), np.float64(-2.101319)], [np.float64(-1.21457), np.float64(-0.625842), np.float64(0.497119)], [np.float64(-0.507723), np.float64(-0.460988), np.float64(2.921708)], [np.float64(0.299642), np.float64(-0.615226), np.float64(-0.189392)], [np.float64(-1.029995), np.float64(0.28537), np.float64(1.78934)], [np.float64(0.359585), np.float64(-0.04706), np.float64(3.024749)]])

