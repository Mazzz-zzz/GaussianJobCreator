db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502823922432230600001/kinbot.db')
label = '1502984102222700000001_well'
logfile = '1502984102222700000001_well.log'

mol = Atoms(symbols=[np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')], positions=[[np.float64(-1.018735), np.float64(-0.094839), np.float64(0.634746)], [np.float64(-1.702306), np.float64(0.487162), np.float64(-0.341182)], [np.float64(-1.523344), np.float64(0.273061), np.float64(1.787247)], [np.float64(-1.129746), np.float64(-1.39479), np.float64(0.507152)], [np.float64(1.168111), np.float64(0.322899), np.float64(-0.743682)], [np.float64(0.782491), np.float64(-0.773922), np.float64(-1.554895)], [np.float64(0.293617), np.float64(0.30943), np.float64(0.623093)], [np.float64(2.491832), np.float64(0.55471), np.float64(-0.302827)], [np.float64(0.668714), np.float64(1.462516), np.float64(-1.280495)]])

