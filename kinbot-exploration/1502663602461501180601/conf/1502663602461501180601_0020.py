from ase import Atoms
from ase.db import connect

from kinbot.ase_modules.calculators.gaussian import Gaussian
from kinbot import reader_gauss
from kinbot.utils import iowait

db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502663602461501180601/kinbot.db')
label = 'conf/1502663602461501180601_0020'
logfile = 'conf/1502663602461501180601_0020.log'

mol = Atoms(symbols=[np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')], positions=[[np.float64(3.9890638956868747), np.float64(3.176769226139168), np.float64(-0.3795752380031918)], [np.float64(4.407339192625541), np.float64(4.388283143512923), np.float64(-0.08464950708509522)], [np.float64(4.820659652035578), np.float64(2.6390638868324197), np.float64(-1.2566277615933397)], [np.float64(4.018499254958709), np.float64(2.4352210783191772), np.float64(0.7153049061894421)], [np.float64(1.9302047513622616), np.float64(1.9126962805152683), np.float64(-1.3484083097269204)], [np.float64(0.9665466524426016), np.float64(0.0), np.float64(0.0)], [np.float64(2.7267858503693567), np.float64(3.295914311586077), np.float64(-0.8839970218847285)], [np.float64(1.236464693889124), np.float64(1.4279017911844194), np.float64(0.0)], [np.float64(0.0), np.float64(0.0), np.float64(0.0)]])

