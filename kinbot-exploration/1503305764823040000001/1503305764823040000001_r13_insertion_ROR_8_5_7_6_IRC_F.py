db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1503305764823040000001/kinbot.db')
label = '1503305764823040000001_r13_insertion_ROR_8_5_7_6_IRC_F'
logfile = '1503305764823040000001_r13_insertion_ROR_8_5_7_6_IRC_F.log'

