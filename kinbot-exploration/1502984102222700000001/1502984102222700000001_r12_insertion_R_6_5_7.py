db = connect('/home/akhalilov/GaussianJobCreator/kinbot-exploration/1502984102222700000001/kinbot.db')
label = '1502984102222700000001_r12_insertion_R_6_5_7'
logfile = '1502984102222700000001_r12_insertion_R_6_5_7.log'

atom = [np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')]
geom = [[np.float64(1.35313), np.float64(2.315069), np.float64(1.20443)], [np.float64(0.033048), np.float64(2.235815), np.float64(1.311126)], [np.float64(1.690565), np.float64(3.536537), np.float64(0.847517)], [np.float64(1.909024), np.float64(2.025703), np.float64(2.351014)], [np.float64(1.279447), np.float64(-0.180684), np.float64(-0.205291)], [np.float64(2.483142), np.float64(-0.096302), np.float64(0.949219)], [np.float64(1.7827), np.float64(1.500604), np.float64(0.194718)], [np.float64(1.505988), np.float64(-0.295203), np.float64(-1.49709)], [np.float64(0.193155), np.float64(-0.198159), np.float64(0.471562)]]
