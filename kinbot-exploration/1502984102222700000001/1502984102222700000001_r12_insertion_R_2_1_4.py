label = '1502984102222700000001_r12_insertion_R_2_1_4'
logfile = '1502984102222700000001_r12_insertion_R_2_1_4.log'

atom = [np.str_('C'), np.str_('F'), np.str_('F'), np.str_('F'), np.str_('S'), np.str_('O'), np.str_('O'), np.str_('O'), np.str_('H')]
